import assert from 'node:assert/strict'
import { mkdtempSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'
import { _electron } from 'playwright'

const userData = mkdtempSync(join(tmpdir(), 'devtoolkit-launcher-'))
writeFileSync(join(userData, 'config.json'), JSON.stringify({ activePluginId: 'quick-launcher', theme: 'light' }))
const env = { ...process.env, DEVTOOLKIT_TEST_DATA: userData }; delete env.ELECTRON_RUN_AS_NODE
const launch = () => _electron.launch({ args: [resolve('tests/fixtures/launcher-bootstrap.mjs')], env })
let app = await launch()
const errors = []
try {
  let page = await app.firstWindow(); page.setDefaultTimeout(15000); page.on('pageerror', e => errors.push(e.message))
  await page.getByRole('heading', { name: '快捷启动', exact: true }).waitFor()
  await page.getByRole('switch', { name: '开启快捷启动' }).click()
  assert.equal(await app.evaluate(({ globalShortcut }) => globalShortcut.isRegistered('Alt+Space')), true)
  await app.evaluate(() => globalThis.triggerLauncherShortcut('Alt+Space'))
  for (let i = 0; i < 50 && !app.windows().some(w => w.url().includes('surface=launcher')); i++) await page.waitForTimeout(100)
  const launcher = app.windows().find(w => w.url().includes('surface=launcher')); assert.ok(launcher)
  launcher.setDefaultTimeout(15000); launcher.on('pageerror', e => errors.push(e.message))
  const input = launcher.getByRole('combobox', { name: '搜索快捷功能' })
  await input.waitFor()
  const visible = () => app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().find(w => w.webContents.getURL().includes('surface=launcher')).isVisible())
  await launcher.waitForFunction(() => document.documentElement.classList.contains('light'))
  await input.press('ArrowDown')
  assert.equal(await launcher.getByRole('option').nth(1).getAttribute('aria-selected'), 'true')
  await input.press('ArrowUp')
  assert.equal(await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().find(w => w.webContents.getURL().includes('surface=launcher')).isAlwaysOnTop()), true)
  await input.fill('(128 + 32) / 4'); await input.press('Enter')
  await launcher.getByRole('status').waitFor()
  assert.equal(await app.evaluate(({ clipboard }) => clipboard.readText()), '40')
  await launcher.getByRole('option').first().screenshot({ path: 'out/test-artifacts/launcher-calculator-result.png', animations: 'disabled' })
  await launcher.screenshot({ path: 'out/test-artifacts/launcher-calculator-light.png', animations: 'disabled' })
  await input.fill('uuid'); await input.press('Enter')
  assert.match(await app.evaluate(({ clipboard }) => clipboard.readText()), /^[\da-f]{8}-[\da-f-]{27}$/)
  await input.fill('无匹配的网页关键词')
  assert.deepEqual(await app.evaluate(() => globalThis.launcherExternal), [], 'Typing never sends a web request')
  await input.press('Enter')
  assert.equal((await app.evaluate(() => globalThis.launcherExternal))[0].url, 'https://www.bing.com/search?q=' + encodeURIComponent('无匹配的网页关键词'))
  assert.equal(await visible(), false)
  await app.evaluate(() => globalThis.triggerLauncherShortcut('Alt+Space'))
  await input.fill('ssh'); await input.press('Enter')
  await page.waitForFunction(() => document.querySelector('nav button[aria-current="page"]')?.textContent.includes('SSH Connections'))
  assert.equal(await visible(), false)
  await page.getByRole('button', { name: '快捷启动', exact: true }).click()
  await page.getByRole('checkbox', { name: '网页搜索', exact: false }).uncheck()
  await app.evaluate(() => globalThis.triggerLauncherShortcut('Alt+Space'))
  await input.fill('完全不匹配的内容')
  await launcher.getByText('没有匹配的功能', { exact: true }).waitFor()
  assert.equal(await page.evaluate(async () => { try { await window.api.invoke('launcher:run', 'web:search', 'x'); return false } catch { return true } }), true)
  assert.equal(await page.evaluate(async () => { try { await window.api.invoke('launcher:run', 'shell:execute', 'cmd'); return false } catch { return true } }), true)
  await input.fill('下载'); await input.press('Enter')
  assert.ok((await app.evaluate(() => globalThis.launcherExternal)).at(-1).path)
  await app.evaluate(() => globalThis.triggerLauncherShortcut('Alt+Space'))
  await input.fill('随手记'); await input.press('Enter')
  assert.equal((await page.evaluate(() => window.api.invoke('desktop:get'))).settings.widgets.note.enabled, true)
  await app.evaluate(() => globalThis.triggerLauncherShortcut('Alt+Space'))
  await input.fill('')
  await page.evaluate(() => window.api.invoke('app:save-theme', 'dark'))
  await launcher.waitForFunction(() => document.documentElement.classList.contains('dark'))
  await launcher.screenshot({ path: 'out/test-artifacts/launcher-dark.png', animations: 'disabled' })
  await input.fill('uuid')
  const previousClipboard = await app.evaluate(({ clipboard }) => clipboard.readText())
  await launcher.getByRole('button', { name: '快捷启动设置', exact: true }).press('Enter')
  assert.equal(await app.evaluate(({ clipboard }) => clipboard.readText()), previousClipboard, 'Settings button Enter must not execute the selected command')
  assert.equal(await visible(), false)
  await app.evaluate(() => globalThis.triggerLauncherShortcut('Alt+Space'))
  await page.evaluate(() => window.api.invoke('launcher:update', { hideOnBlur: false }))
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().find(w => w.webContents.getURL().includes('surface=launcher')).emit('blur'))
  assert.equal(await visible(), true)
  await page.evaluate(() => window.api.invoke('launcher:update', { hideOnBlur: true }))
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().find(w => w.webContents.getURL().includes('surface=launcher')).emit('blur'))
  assert.equal(await visible(), false)
  await app.evaluate(() => globalThis.triggerLauncherShortcut('Alt+Space'))
  await input.press('Escape'); assert.equal(await visible(), false)
  await app.evaluate(() => globalThis.triggerLauncherShortcut('Alt+Space'))
  await launcher.waitForFunction(() => document.activeElement?.getAttribute('aria-label') === '搜索快捷功能')
  await app.evaluate(() => globalThis.triggerLauncherShortcut('Alt+Space'))
  await page.waitForTimeout(100); assert.equal(await visible(), false)
  await page.getByRole('switch', { name: '开启快捷启动' }).click()
  assert.equal(await app.evaluate(({ globalShortcut }) => globalShortcut.isRegistered('Alt+Space')), false)
  await app.evaluate(() => { globalThis.launcherConflict = true })
  await page.getByRole('switch', { name: '开启快捷启动' }).click()
  await page.getByRole('alert').waitFor()
  assert.equal((await page.evaluate(() => window.api.invoke('launcher:get'))).settings.enabled, false)
  await app.evaluate(() => { globalThis.launcherConflict = false })
  await page.getByRole('switch', { name: '开启快捷启动' }).click()
  await page.screenshot({ path: 'out/test-artifacts/launcher-settings.png', animations: 'disabled' })
  await app.close(); app = await launch(); page = await app.firstWindow()
  await page.getByRole('heading', { name: '快捷启动', exact: true }).waitFor()
  const restored = await page.evaluate(() => window.api.invoke('launcher:get'))
  assert.equal(restored.active, true); assert.equal(restored.settings.groups.includes('web'), false)
  await page.evaluate(() => window.api.invoke('launcher:update', { enabled: false }))
  assert.deepEqual(errors, [])
  console.log('PASS: Alt+Space registration/toggle/conflict/restart, theme, keyboard search, arithmetic/UUID copy, page navigation, folders, widgets, disabled groups and explicit web search')
} finally { await app.close() }

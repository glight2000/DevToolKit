  assert.ok(identity.name >= identity.plan, 'Account name sits below the plan')
  assert.equal(identity.width, 150)
  assert.equal(await codexPanel.locator('.dock-coupons li').count(), 2, 'Coupon details are visible without opening statistics')
  assert.equal(await codexPanel.locator('.dock-username').evaluate(el => getComputedStyle(el).whiteSpace), 'normal')
  const contentSize = await codexPanel.locator('.dock-account-body').evaluate(el => ({ scroll: el.scrollHeight, visible: el.clientHeight }))
  assert.ok(contentSize.scroll <= contentSize.visible + 1, 'Two quota windows, coupons and next refresh fit without vertical scrolling')

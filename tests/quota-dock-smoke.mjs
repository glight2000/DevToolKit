  await page.getByRole('heading', { name: 'AI 订阅', exact: true }).waitFor()
  await page.waitForFunction(async () => (await window.api.invoke('subscriptions:list')).some(r => r.connectionId === 'FixtureUbuntu' && r.accounts.length === 2 && !r.refreshing))

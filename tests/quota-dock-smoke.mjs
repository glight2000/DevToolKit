  await page.evaluate(() => window.api.invoke('app:save-theme', 'dark'))
  await widget.waitForFunction(() => document.documentElement.classList.contains('dark'))
  assert.equal(await widget.locator('.quota-message,.quota-footnote,.quota-refresh-status').count(), 0, 'Dock descriptions belong in hover hints')
  await codexPanel.locator('.dock-values .dock-hint').first().hover()

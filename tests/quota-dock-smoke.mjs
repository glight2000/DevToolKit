  assert.equal(await codexPanel.locator('.dock-plan').innerText(), 'pro')
  assert.equal(await codexPanel.locator('.dock-username').innerText(), 'developer@example.test')
  await widget.waitForFunction(() => document.querySelector('.floating-widget')?.getAttribute('data-motion') === 'idle')
